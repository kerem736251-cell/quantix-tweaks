using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using QuantixTweakingUtility.Models;

namespace QuantixTweakingUtility.Services;

public sealed class CleanupService : ICleanupService
{
	private readonly ILoggingService _logging;

	private readonly IReadOnlyList<CleanupTarget> _targets;

	public CleanupService(ILoggingService logging)
	{
		_logging = logging;
		string folderPath = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
		string folderPath2 = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
		_targets = new List<CleanupTarget>
		{
			new CleanupTarget
			{
				Id = "user-temp",
				Name = "Temporary Files",
				Description = "Files left by installers and applications in your user temporary folder.",
				Paths = new string[1] { Path.Combine(folderPath, "Temp") },
				IsCleanable = true
			},
			new CleanupTarget
			{
				Id = "windows-temp",
				Name = "Windows Cache",
				Description = "Temporary files created by Windows. Files in use are always skipped.",
				Paths = new string[1] { Path.Combine(folderPath2, "Temp") },
				IsCleanable = true
			},
			new CleanupTarget
			{
				Id = "shader-caches",
				Name = "Shader Caches",
				Description = "Known DirectX, NVIDIA and AMD shader-cache folders. Games rebuild these caches; first launches may stutter. Locked files and directory links are skipped.",
				Paths = ShaderCacheLocations.Resolve(folderPath, Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData)),
				IsCleanable = true
			},
			new CleanupTarget
			{
				Id = "quantix-logs",
				Name = "Application Logs",
				Description = "Diagnostic logs generated by Quantix. Current and locked log files are skipped.",
				Paths = new string[1] { Path.Combine(folderPath, "Quantix", "Logs") },
				IsCleanable = true
			},
			new CleanupTarget
			{
				Id = "browser-cache",
				Name = "Browser Cache",
				Description = "Browser profiles are not cleaned automatically because that can sign you out or remove active sessions.",
				IsCleanable = false,
				UnavailableReason = "Managed in your browser"
			},
			new CleanupTarget
			{
				Id = "recycle-bin",
				Name = "Recycle Bin",
				Description = "Recycle Bin contents are intentionally left to Windows so you can review them before deletion.",
				IsCleanable = false,
				UnavailableReason = "Use Windows Storage settings"
			},
			new CleanupTarget
			{
				Id = "update-cache",
				Name = "Update Cache",
				Description = "Windows Update cache requires stopping system services and is not removed by Quantix.",
				IsCleanable = false,
				UnavailableReason = "Requires service coordination"
			}
		};
	}

	public IReadOnlyList<CleanupTarget> GetTargets()
	{
		return _targets;
	}

	public async Task<IReadOnlyList<CleanupScanResult>> ScanAsync()
	{
		List<CleanupScanResult> scans = new List<CleanupScanResult>();
		foreach (CleanupTarget target in _targets)
		{
			if (!target.IsCleanable)
			{
				scans.Add(new CleanupScanResult
				{
					Target = target,
					Status = target.UnavailableReason
				});
				continue;
			}
			string preserveFile = ((target.Id == "quantix-logs") ? _logging.CurrentLogFilePath : null);
			long reclaimableBytes = await Task.Run(() => target.Paths.Sum((string path) => MeasureDirectory(path, preserveFile)));
			scans.Add(new CleanupScanResult
			{
				Target = target,
				ReclaimableBytes = reclaimableBytes,
				Status = "Ready to clean"
			});
		}
		return scans;
	}

	public async Task<CleanupActionResult> CleanAsync(IEnumerable<string> targetIds)
	{
		List<CleanupTarget> selected = _targets.Where((CleanupTarget target) => target.IsCleanable && targetIds.Contains<string>(target.Id, StringComparer.Ordinal)).ToList();
		if (selected.Count == 0)
		{
			return new CleanupActionResult
			{
				Success = false,
				Message = "Choose at least one scanned cleanup category."
			};
		}
		try
		{
			long num = 0L; int files = 0, skipped = 0;
			foreach (CleanupTarget item in selected)
			{
				string preserveFile = ((item.Id == "quantix-logs") ? _logging.CurrentLogFilePath : null);
				foreach (string path in item.Paths)
				{
					var result = await Task.Run(() => CacheFileCleaner.Clear(path, preserveFile));
					num += result.Bytes; files += result.Files; skipped += result.Skipped;
				}
			}
			_logging.Info("Cleanup", $"Cleaned {selected.Count} safe cache target(s), reclaiming {num} bytes.");
			return new CleanupActionResult
			{
				Success = files > 0 || skipped == 0,
				ReclaimedBytes = num,
				Message = $"Removed {files} cache files ({num:N0} bytes). Skipped {skipped} locked, linked or inaccessible entries."
			};
		}
		catch (Exception ex)
		{
			_logging.Error("Cleanup", "Cleanup failed.", ex);
			return new CleanupActionResult
			{
				Success = false,
				Message = "Some files could not be cleaned. See the log for details."
			};
		}
	}

	private static long MeasureDirectory(string path, string? preserveFile = null) => CacheFileCleaner.Inspect(path, preserveFile).Bytes;

}
